package juloo.keyboard2.suggestions;

import java.nio.ByteBuffer;
import java.nio.charset.StandardCharsets;

/** Probabilities of words given the previous word, read from a '.bigrams'
    file generated by 'scripts/gen_bigrams.py'. The file is not decoded, the
    queries look into the bytes directly.

    Probabilities are expressed as costs: -log2(probability) in quarters of
    bits. Lower is more likely. */
public final class Bigrams
{
  /** Cost of a word that is not in the file. */
  public static final int MAX_COST = 255;
  /** Number of cost units in a bit. A difference of [COST_UNIT] means twice
      as likely. */
  public static final int COST_UNIT = 4;

  public static Bigrams of_bytes(byte[] data) throws Exception
  {
    return new Bigrams(ByteBuffer.wrap(data));
  }

  /** Number of words. */
  public int length() { return _n; }

  /** Index of the given word or [-1]. */
  public int find(String word)
  {
    byte[] w = word.getBytes(StandardCharsets.UTF_8);
    int lo = 0;
    int hi = _n - 1;
    while (lo <= hi)
    {
      int mid = (lo + hi) >>> 1;
      int c = compare_word(mid, w);
      if (c < 0)
        lo = mid + 1;
      else if (c > 0)
        hi = mid - 1;
      else
        return mid;
    }
    return -1;
  }

  public String word(int index)
  {
    int start = word_offset(index);
    int len = word_offset(index + 1) - start;
    return new String(_b.array(), _b.arrayOffset() + _words + start, len,
        StandardCharsets.UTF_8);
  }

  /** Cost of a word, regardless of the context. */
  public int unigram_cost(int index)
  {
    if (index < 0)
      return MAX_COST;
    return _b.get(_unigram_costs + index) & 0xFF;
  }

  /** Cost of the word [index] after the word [context]. Unlisted pairs are
      estimated from the unigram cost. */
  public int cost(int context, int index)
  {
    if (index < 0)
      return MAX_COST;
    if (context >= 0)
    {
      int lo = entries_start(context);
      int hi = entries_start(context + 1) - 1;
      while (lo <= hi)
      {
        int mid = (lo + hi) >>> 1;
        int w = entry_word(mid);
        if (w < index)
          lo = mid + 1;
        else if (w > index)
          hi = mid - 1;
        else
          return entry_cost(mid);
      }
    }
    return Math.min(MAX_COST, unigram_cost(index) + _backoff);
  }

  /** Words that commonly follow [context] are the entries from
      [entries_start(context)] to [entries_start(context + 1)]. */
  public int entries_start(int context)
  {
    return _b.getInt(_entry_offsets + context * 4);
  }

  /** The word index of an entry. */
  public int entry_word(int entry)
  {
    return _b.getInt(_entries + entry * 4) >>> 8;
  }

  public int entry_cost(int entry)
  {
    return _b.getInt(_entries + entry * 4) & 0xFF;
  }

  /** Private */

  final ByteBuffer _b;
  final int _n;
  final int _backoff;
  // Positions of the sections of the file.
  final int _word_offsets;
  final int _words;
  final int _unigram_costs;
  final int _entry_offsets;
  final int _entries;

  Bigrams(ByteBuffer b) throws Exception
  {
    _b = b;
    if (b.capacity() < 10 || b.get(0) != 'U' || b.get(1) != 'K'
        || b.get(2) != 'B' || b.get(3) != 'G')
      throw new Exception("Not a bigrams file");
    if (b.get(4) != 1)
      throw new Exception("Unsupported bigrams file version");
    _n = b.getInt(5);
    _backoff = b.get(9) & 0xFF;
    _word_offsets = 10;
    _words = _word_offsets + (_n + 1) * 4;
    _unigram_costs = _words + word_offset(_n);
    _entry_offsets = _unigram_costs + _n;
    _entries = _entry_offsets + (_n + 1) * 4;
    if (_entries + entries_start(_n) * 4 != b.capacity())
      throw new Exception("Truncated bigrams file");
  }

  int word_offset(int index)
  {
    return _b.getInt(_word_offsets + index * 4);
  }

  /** Compare word [index] with the UTF-8 encoded [w] by unsigned byte
      values, which is the order of the words in the file. */
  int compare_word(int index, byte[] w)
  {
    int start = _words + word_offset(index);
    int len = word_offset(index + 1) - word_offset(index);
    int l = Math.min(len, w.length);
    for (int i = 0; i < l; i++)
    {
      int c = (_b.get(start + i) & 0xFF) - (w[i] & 0xFF);
      if (c != 0)
        return c;
    }
    return len - w.length;
  }
}
